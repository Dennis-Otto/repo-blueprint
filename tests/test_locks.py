@needs_git
def test_a_lock_file_that_is_no_text_stops_the_check(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = repository(tmp_path, {})
    (root / "requirements.txt").write_bytes(b"\xff\xfe")

    assert main(["locks"], root=root) == 2
    assert capsys.readouterr().err.startswith("blueprint.py: 'utf-8' codec")


def test_a_folder_without_git_stops_the_check(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    # Git looks for a repository above the folder as well, which the test machine
    # may have.
    monkeypatch.setenv("GIT_CEILING_DIRECTORIES", str(tmp_path.parent))

    assert main(["locks"], root=tmp_path) == 2
    # The words of the failed command, which Python 3.15 no longer puts in quotes.
    err = capsys.readouterr().err
    assert err.startswith("blueprint.py: Command "), err
    assert "['git', 'ls-files', " in err, err
    assert err.endswith(" returned non-zero exit status 128.\n"), err


def test_a_skipped_lock_file_reads_as_one_sentence() -> None:
    skipped = Skipped("requirements.txt", ["no source file", "no Python in the header"])

    assert str(skipped) == (
        "requirements.txt: Renovate skips it, for no source file; no Python in the "
        "header."
    )
