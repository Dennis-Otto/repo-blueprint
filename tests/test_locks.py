def test_the_pattern_is_that_of_the_rules_of_renovate() -> None:
    # The files that the manager pip-compile of Renovate finds, and those that the
    # rules leave out, as the blueprint and every repository have them.
    for name in (
        ".github/renovate-blueprint.json5",
        "template/.github/renovate-blueprint.json5.jinja",
    ):
        rules = (ROOT / name).read_text(encoding="utf-8")
        pattern = re.search(
            r'"pip-compile": \{ managerFilePatterns: \["/(.+)/"\] \}', rules
        )
        ignored = re.search(r"^  ignorePaths: (\[.*\]),$", rules, re.M)
        assert pattern, name
        assert ignored, name
        assert json.loads(f'"{pattern[1]}"') == locks.PATTERN.pattern, name
        assert set(json.loads(ignored[1])) == {
            f"**/{folder}/**" for folder in locks.IGNORED
        }, name


