REQUIREMENTS_HEADER = WITH_EQUAL_SIGN.replace("requirements-test", "requirements")
PIP_REQUIREMENTS_HEADER = PIP_COMPILE.replace("requirements-dev", "requirements")
PASSED = (
    "Compiled again with the command in its header, each of the {} compared lock "
    "file(s) of pip-compile keeps its pins.\n"
)


def lock(header: str, *pins: str) -> str:
    """A lock file with this header and these pins, each with a hash."""
    return header + "".join(
        f"{pin} \\\n    --hash=sha256:{'0' * 64}\n    # via -r requirements.in\n"
        for pin in pins
    )


class FakeUv:
    """Stands in for uv pip compile: keeps what it was asked and writes the lock file
    that it found into its output file, as uv does."""

    def __init__(self) -> None:
        self.answers()
        self.commands: list[list[str]] = []
        self.folders: list[Path] = []
        self.preferred: list[str] = []
        self.constraints: list[str] = []
        self.real = subprocess.run

    def answers(self, body: str = "", returncode: int = 0, said: str = "") -> None:
        """What it does from now on."""
        self.body = body
        self.returncode = returncode
        self.said = said

    def __call__(
        self, command: list[str], **options: Any
    ) -> subprocess.CompletedProcess[str]:
        if command[0] != "uv":
            return self.real(command, **options)
        self.commands.append(command)
        self.folders.append(Path(options["cwd"]))
        output = Path(command[-1].removeprefix("--output-file="))
        self.preferred.append(output.read_text(encoding="utf-8"))
        self.constraints += [
            Path(part.removeprefix("--constraint=")).read_text(encoding="utf-8")
            for part in command
            if part.startswith("--constraint=")
        ]
        if self.returncode == 0:
            output.write_text(self.body, encoding="utf-8", newline="\n")
        return subprocess.CompletedProcess(command, self.returncode, "", self.said)


