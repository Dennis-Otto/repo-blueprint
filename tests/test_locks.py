NO_INDEX = "--no-index\n--find-links wheels\n"
BOTH_HEADERS = [REQUIREMENTS_HEADER, PIP_REQUIREMENTS_HEADER]


def wheel(
    root: Path,
    name: str,
    version: str,
    *requires: str,
    python: str = "",
    tag: str = "py3-none-any",
) -> None:
    """A wheel on the disk, in the package index of the sources of these tests."""
    folder = root / "wheels"
    folder.mkdir(exist_ok=True)
    info = f"{name}-{version}.dist-info"
    metadata = f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
    metadata += f"Requires-Python: {python}\n" if python else ""
    metadata += "".join(f"Requires-Dist: {require}\n" for require in requires)
    with zipfile.ZipFile(folder / f"{name}-{version}-{tag}.whl", "w") as archive:
        archive.writestr(f"{name}.py", "")
        archive.writestr(f"{info}/METADATA", metadata)
        archive.writestr(
            f"{info}/WHEEL",
            f"Wheel-Version: 1.0\nGenerator: tests\nRoot-Is-Purelib: true\nTag: {tag}\n",
        )
        archive.writestr(f"{info}/RECORD", "")


def fixed(root: Path, capsys: pytest.CaptureFixture[str]) -> str:
    """The lock file that the fix leaves."""
    assert main(["locks", "--compile", "--fix"], root=root) == 0
    capsys.readouterr()
    return (root / "requirements.txt").read_text(encoding="utf-8")


def sources(root: Path, *requirements: str) -> None:
    """Writes the sources of the lock file of a test."""
    (root / "requirements.in").write_text(
        NO_INDEX + "".join(f"{line}\n" for line in requirements),
        encoding="utf-8",
        newline="\n",
    )


