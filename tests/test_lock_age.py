"""The age of what the weekly refresh of the lock files brings: the step of the check
dependency-review that holds a refresh with a version younger than a week."""

from __future__ import annotations

import io
import json
import shutil
import subprocess
import urllib.error
import urllib.request
from collections.abc import Callable
from datetime import UTC, datetime, timedelta
from email.message import Message
from pathlib import Path
from typing import Any

import pytest

from blueprint import github, lock_age
from blueprint.cli import main
from blueprint.lock_age import Added, Undated

GIT = shutil.which("git")
pytestmark = pytest.mark.skipif(
    GIT is None, reason="the check compares two commits of git"
)

HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv pip compile --generate-hashes --python-version=3.12"
    " --output-file=requirements.txt requirements.in\n"
)
NOW = datetime(2026, 11, 9, 15, 30, tzinfo=UTC)
OLD = "2026-10-01T12:00:00.000Z"
YOUNG = "2026-11-07T08:15:00.000Z"


def npm_lock(*packages: tuple[str, dict[str, Any]]) -> str:
    """A package-lock.json of npm 7 or newer with these entries besides the root."""
    entries: dict[str, Any] = {"": {"name": "web", "version": "1.0.0"}}
    entries.update(packages)
    return json.dumps({"name": "web", "lockfileVersion": 3, "packages": entries})


def registry(name: str, version: str) -> tuple[str, dict[str, Any]]:
    """An entry of package-lock.json that npm installs from its registry."""
    return (
        f"node_modules/{name}",
        {
            "version": version,
            "resolved": f"https://registry.npmjs.org/{name}/-/{name}-{version}.tgz",
        },
    )


def commit(root: Path, files: dict[str, str]) -> None:
    """A commit of the repository at root with these files."""
    assert GIT
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text, encoding="utf-8", newline="\n")
    subprocess.run([GIT, "add", "-A"], cwd=root, check=True)
    subprocess.run(
        [
            *(GIT, "-c", "user.name=Test", "-c", "user.email=test@example.com"),
            *("commit", "--quiet", "--no-gpg-sign", "-m", "change"),
        ],
        cwd=root,
        check=True,
    )


def refresh(
    tmp_path: Path, main_files: dict[str, str], refresh: dict[str, str]
) -> Path:
    """A repository whose main has main_files and whose head, a commit of the
    refresh on top of it, changes them to refresh."""
    assert GIT
    subprocess.run([GIT, "init", "--quiet", str(tmp_path)], check=True)
    commit(tmp_path, main_files)
    commit(tmp_path, refresh)
    return tmp_path


class Registries:
    """Stands in for PyPI and the registry of npm: answers each address with its JSON,
    or raises the error that it holds for it, and keeps what it was asked."""

    def __init__(self, answers: dict[str, Any]) -> None:
        self.answers = answers
        self.asked: list[str] = []

    def __call__(self, url: str, timeout: float) -> io.BytesIO:
        assert timeout == lock_age.TIMEOUT
        self.asked.append(url)
        answer = self.answers[url]
        if isinstance(answer, list):
            answer = answer.pop(0)
        if isinstance(answer, OSError):
            raise answer
        return io.BytesIO(json.dumps(answer).encode("utf-8"))


def pypi(*uploads: str) -> dict[str, Any]:
    """PyPI's answer for a version with a file for each upload."""
    return {"urls": [{"upload_time_iso_8601": upload} for upload in uploads]}


def refused(code: int) -> urllib.error.HTTPError:
    """The answer of a registry that refuses with this status."""
    return urllib.error.HTTPError(
        "https://example.org", code, "refused", Message(), io.BytesIO(b"")
    )


@pytest.fixture(autouse=True)
def no_pause(monkeypatch: pytest.MonkeyPatch) -> list[float]:
    """The pauses between the attempts, without waiting for them."""
    pauses: list[float] = []
    monkeypatch.setattr(github, "sleep", pauses.append)
    return pauses


def test_the_check_finds_what_the_refresh_adds_to_each_lock_file(
    tmp_path: Path,
) -> None:
    root = refresh(
        tmp_path,
        {
            "requirements.in": "alpha\nbeta\n",
            "requirements.txt": HEADER + "alpha==1.0\nbeta==2.0\n",
            "web/package.json": "{}\n",
            "web/package-lock.json": npm_lock(
                registry("left-pad", "1.2.0"),
                ("packages/tool", {"version": "1.0.0"}),
            ),
            "docs/requirements.txt": HEADER + "gamma==1.0\n",
        },
        {
            # alpha moves, beta stays, and delta comes by an address of its own.
            "requirements.txt": HEADER
            + "alpha==1.5\nbeta==2.0\ndelta @ https://example.org/delta.whl\n",
            "web/package-lock.json": npm_lock(
                registry("left-pad", "1.3.0"),
                registry("@scope/kit", "2.0.0"),
                registry("@scope/kit/node_modules/inner", "0.1.0"),
                ("packages/tool", {"version": "1.1.0"}),
                ("node_modules/tool", {"resolved": "packages/tool", "link": True}),
                (
                    "node_modules/from-git",
                    {"version": "3.0.0", "resolved": "git+https://example.org/x.git"},
                ),
                ("node_modules/bundled", {"version": "4.0.0", "inBundle": True}),
            ),
        },
    )

    versions, problems = lock_age.added(root, "HEAD~1")

    assert versions == [
        Added("requirements.txt", "pip", "alpha", "1.5"),
        Added("requirements.txt", "pip", "delta", ""),
        Added("web/package-lock.json", "npm", "@scope/kit", "2.0.0"),
        Added("web/package-lock.json", "npm", "bundled", "4.0.0"),
        Added("web/package-lock.json", "npm", "from-git", ""),
        Added("web/package-lock.json", "npm", "inner", "0.1.0"),
        Added("web/package-lock.json", "npm", "left-pad", "1.3.0"),
    ]
    assert problems == []
    assert str(versions[0]) == "requirements.txt: alpha 1.5"


@pytest.mark.parametrize(
    ("name", "text"),
    [
        ("requirements.txt", HEADER + "--index-url https://example.org/simple\n"),
        ("web/package-lock.json", "{ not JSON"),
        ("web/package-lock.json", json.dumps({"lockfileVersion": 1})),
        ("web/package-lock.json", json.dumps(["no", "lock", "file"])),
    ],
    ids=["an index", "no JSON", "npm 6", "a list"],
)
def test_a_lock_file_whose_versions_the_check_cant_read_holds_the_refresh(
    tmp_path: Path, name: str, text: str
) -> None:
    root = refresh(
        tmp_path,
        {"requirements.in": "alpha\n", "README.md": "# Demo\n"},
        {name: text},
    )

    assert lock_age.added(root, "HEAD~1") == (
        [],
        [f"{name}: the check can't read its versions."],
    )


def test_a_file_of_another_package_manager_holds_the_refresh(tmp_path: Path) -> None:
    root = refresh(
        tmp_path,
        {"composer.lock": "{}\n"},
        {"composer.lock": '{"packages": []}\n'},
    )

    assert lock_age.added(root, "HEAD~1") == (
        [],
        [
            "composer.lock: the refresh changes it, and the check can't date the "
            "versions of such a file."
        ],
    )


def test_a_version_of_a_week_ago_passes_and_a_younger_one_holds_the_refresh() -> None:
    answers = Registries(
        {
            "https://pypi.org/pypi/alpha/1.5/json": pypi(YOUNG, OLD),
            "https://pypi.org/pypi/beta/2.0/json": pypi(OLD),
            "https://registry.npmjs.org/@scope%2Fkit": {
                "time": {"2.0.0": "2026-11-02T15:29:00Z", "1.0.0": YOUNG}
            },
            "https://registry.npmjs.org/left-pad": {"time": {"1.3.0": YOUNG}},
        }
    )
    versions = [
        Added("requirements.txt", "pip", "alpha", "1.5"),
        Added("requirements.txt", "pip", "beta", "2.0"),
        Added("web/package-lock.json", "npm", "@scope/kit", "2.0.0"),
        Added("web/package-lock.json", "npm", "left-pad", "1.3.0"),
        Added("web/package-lock.json", "npm", "left-pad", "1.3.0"),
    ]

    # A version counts from its first file: alpha 1.5 got a new wheel recently, but
    # came out long before. The registry, not the author, sets each date.
    assert lock_age.young(versions, NOW, answers) == [
        "web/package-lock.json: left-pad 1.3.0: released 2026-11-07 08:15 UTC, less "
        "than a week ago."
    ]
    # Each version once.
    assert sorted(answers.asked) == sorted(answers.answers)


@pytest.mark.parametrize(
    ("version", "answer", "why"),
    [
        (
            Added("r.txt", "pip", "delta", ""),
            {},
            "it comes from no registry but by an address of its own",
        ),
        (Added("r.txt", "pip", "alpha", "1.5"), pypi(), "PyPI names no file of it"),
        (Added("r.txt", "pip", "alpha", "1.5"), [], "PyPI names no file of it"),
        (
            Added("p.json", "npm", "kit", "2.0.0"),
            {"time": {"1.0.0": OLD}},
            "the registry of npm names no time of it",
        ),
        (
            Added("p.json", "npm", "kit", "2.0.0"),
            {"time": {"2.0.0": None}},
            "the registry names no date but None",
        ),
        (
            Added("p.json", "npm", "kit", "2.0.0"),
            {"time": {"2.0.0": "yesterday"}},
            "the registry names 'yesterday' as its date",
        ),
        (
            Added("p.json", "npm", "kit", "2.0.0"),
            [],
            "the registry of npm names no time of it",
        ),
    ],
    ids=[
        "an address",
        "no file",
        "no answer of PyPI",
        "no time",
        "no date",
        "no moment",
        "no answer of npm",
    ],
)
def test_a_version_that_the_check_cant_date_holds_the_refresh(
    version: Added, answer: Any, why: str
) -> None:
    def answering(url: str, timeout: float) -> io.BytesIO:
        return io.BytesIO(json.dumps(answer).encode("utf-8"))

    assert lock_age.young([version], NOW, answering) == [
        f"{version}: the check can't learn its release: {why}."
    ]


def test_a_date_without_a_zone_is_one_of_utc() -> None:
    assert lock_age.moment("2026-11-02T15:30:00") == datetime(
        2026, 11, 2, 15, 30, tzinfo=UTC
    )


def test_the_registry_is_asked_again_after_a_failure_that_may_pass(
    no_pause: list[float],
) -> None:
    url = "https://pypi.org/pypi/alpha/1.5/json"
    answers = Registries(
        {url: [refused(503), urllib.error.URLError("timed out"), pypi(OLD)]}
    )

    released = lock_age.released(Added("r.txt", "pip", "alpha", "1.5"), answers)

    assert released == datetime(2026, 10, 1, 12, tzinfo=UTC)
    assert answers.asked == [url, url, url]
    assert no_pause == [lock_age.PAUSE, lock_age.PAUSE]


@pytest.mark.parametrize(
    ("errors", "attempts"),
    [
        ([refused(404)], 1),
        ([urllib.error.URLError("timed out")] * lock_age.ATTEMPTS, lock_age.ATTEMPTS),
    ],
    ids=["a refusal", "an outage"],
)
def test_a_registry_that_doesnt_answer_leaves_the_version_undated(
    errors: list[OSError], attempts: int
) -> None:
    url = "https://pypi.org/pypi/alpha/1.5/json"
    answers = Registries({url: list(errors)})

    with pytest.raises(Undated, match=f"^{url}: "):
        lock_age.released(Added("r.txt", "pip", "alpha", "1.5"), answers)
    assert len(answers.asked) == attempts


def opened_by_urllib(
    monkeypatch: pytest.MonkeyPatch, answers: Callable[[str, float], io.BytesIO]
) -> None:
    """The registries that the command asks, through the opener of urllib."""
    monkeypatch.setattr(urllib.request, "urlopen", answers)


def test_the_check_of_a_refresh_names_each_young_version(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    root = refresh(
        tmp_path,
        {
            "requirements.in": "alpha\n",
            "requirements.txt": HEADER + "alpha==1.0\n",
            "composer.lock": "{}\n",
        },
        {"requirements.txt": HEADER + "alpha==1.5\n", "composer.lock": "[]\n"},
    )
    young = (datetime.now(UTC) - timedelta(days=2)).isoformat()
    opened_by_urllib(
        monkeypatch,
        Registries({"https://pypi.org/pypi/alpha/1.5/json": pypi(young)}),
    )

    assert main(["locks", "--age", "HEAD~1"], root=root) == 1

    lines = capsys.readouterr().out.splitlines()
    assert lines[0] == (
        "composer.lock: the refresh changes it, and the check can't date the "
        "versions of such a file."
    )
    assert lines[1].startswith("requirements.txt: alpha 1.5: released ")
    assert lines[1].endswith(" UTC, less than a week ago.")
    assert lines[2].startswith(
        "The weekly refresh of the lock files merges by itself only from versions "
        "at least a week old"
    )
    assert 'additionalBranchPrefix "review-"' in lines[2]


def test_the_check_passes_a_refresh_of_versions_a_week_old(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    root = refresh(
        tmp_path,
        {"requirements.in": "alpha\n", "requirements.txt": HEADER + "alpha==1.0\n"},
        {"requirements.txt": HEADER + "alpha==1.5\n"},
    )
    opened_by_urllib(
        monkeypatch, Registries({"https://pypi.org/pypi/alpha/1.5/json": pypi(OLD)})
    )

    assert main(["locks", "--age", "HEAD~1"], root=root) == 0

    assert capsys.readouterr().out == (
        "Each of the 1 version(s) that the refresh adds is at least a week old.\n"
    )
